def sendResponse(request, resultCode, data, action="no action"):
    """Стандарт response үүсгэх"""
    response = {}
    
    # resultCode-г зөв төрөлд хөрвүүлэх
    if isinstance(resultCode, (list, dict)):
        resultCode = 400
    elif not isinstance(resultCode, (int, str)):
        resultCode = 500
    
