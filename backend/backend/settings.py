    code_str = str(resultCode)
    
    response["resultCode"] = resultCode
    response["resultMessage"] = resultMessages.get(code_str, f"Unknown status code: {resultCode}")
    response["data"] = data
    
    # data-н хэмжээг тооцоолох
    if isinstance(data, (list, dict, str)):
        response["size"] = len(data)
    else:
        response["size"] = 0
    
    response["action"] = action
    response["curdate"] = datetime.now().strftime('%Y/%m/%d %H:%M:%S')

    return response



